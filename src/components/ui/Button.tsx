import React from 'react';
import { motion, HTMLMotionProps } from 'framer-motion';

interface ButtonProps extends HTMLMotionProps<'button'> {
  variant?: 'primary' | 'secondary' | 'ghost' | 'danger';
  size?: 'sm' | 'md' | 'lg';
}

export const Button: React.FC<ButtonProps> = ({
  variant = 'primary',
  size = 'md',
  children,
  className = '',
  ...props
}) => {
  const baseStyles = 'inline-flex items-center justify-center font-medium rounded-xl transition-all duration-200 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-brand-volcano disabled:opacity-50 disabled:cursor-not-allowed';
  
  const variants = {
    primary: 'bg-volcanic-gradient text-white shadow-volcanic hover:shadow-volcanic-lg hover:brightness-110',
    secondary: 'border border-border-main bg-bg-card hover:bg-bg-hover text-text-primary hover:border-text-secondary',
    ghost: 'text-text-primary hover:bg-bg-hover',
    danger: 'bg-red-600 hover:bg-red-700 text-white shadow-md'
  };

  const sizes = {
    sm: 'px-4 py-2 text-xs',
    md: 'px-6 py-3 text-sm',
    lg: 'px-8 py-4 text-base'
  };

  return (
    <motion.button
      whileHover={{ scale: 1.02 }}
      whileTap={{ scale: 0.98 }}
      className={`${baseStyles} ${variants[variant]} ${sizes[size]} ${className}`}
      {...props}
    >
      {children}
    </motion.button>
  );
};
export default Button;
